/** 生成带 ID 和时间戳的完整 Reference 数组（归一化：year 转 string、Creator 补全字段） */
export function getSeedReferences(): Reference[] {
  const now = new Date().toISOString();
  const stamp = Date.now().toString(36);
  return SEED_REFERENCES.map((r, i) => {
    const creators: Creator[] = r.creators.map((c, ci) => ({
      id: `seed_c_${stamp}_${i}_${ci}`,
      firstName: c.firstName,
      lastName: c.lastName,
      type: 'author',
      order: ci,
    }));
    const ref: Reference = {
      id: `seed_ref_${stamp}_${i}`,
      citeKey: r.citeKey,
      type: r.type,
      title: r.title,
      shortTitle: '',
      abstract: r.abstract,
      creators,
      publication: r.publication,
      volume: r.volume,
      issue: r.issue,
      pages: r.pages,
      publisher: '',
      place: '',
      year: String(r.year),
      date: '',
      accessionDate: '',
      doi: r.doi,
      isbn: '',
      issn: '',
      pmid: '',
      pmcid: '',
      arxivId: '',
      url: r.doi ? `https://doi.org/${r.doi}` : '',
      uri: '',
      collections: [],
      tags: r.tags,
      language: 'zh',
      rights: '',
      attachments: [],
      annotations: [],
      notes: '',
      impactFactor: null,
      jcrQuartile: null,
      openAccess: r.openAccess,
      pageCharge: null,
      reviewWeeks: null,
      pipelineStage: null,
      readStatus: r.readStatus,
      importance: r.importance,
      createdAt: now,
      updatedAt: now,
      source: 'import',
    };
    return ref;
  });
}
