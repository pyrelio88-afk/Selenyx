# Output final TypeScript file
# ============================================================
OUTPUT = os.path.join(BASE, 'frontend', 'src', 'data', 'disciplines.ts')

with open(OUTPUT, 'w', encoding='utf-8') as f:
    f.write('/**\n')
    f.write(' * Selenyx 全学科数据集 —— 按中国学科门类覆盖\n')
    f.write(f' * R83: 深度扩展至 {len(disciplines)} 个学科门类，共 {sum(len(d["glossary"]) for d in disciplines)} 个术语\n')
    f.write(' * 不依赖后端，全部内置在前端\n')
    f.write(' */\n\n')

    f.write('export interface DisciplineGlossary {\n')
    f.write('  term: string;\n  termEn: string;\n  definition: string;\n  category: string;\n}\n\n')
    f.write('export interface DisciplineFormula {\n  name: string;\n  formula: string;\n  description: string;\n  unit?: string;\n  reference?: string;\n}\n\n')
    f.write('export interface DisciplineStandard {\n  name: string;\n  code: string;\n  description: string;\n}\n\n')
    f.write('export interface Discipline {\n')
    f.write('  id: string;\n  name: string;\n  nameEn: string;\n  icon: string;\n  color: string;\n  description: string;\n  glossary: DisciplineGlossary[];\n  formulas: DisciplineFormula[];\n  standards: DisciplineStandard[];\n}\n\n')

    f.write('export const DISCIPLINES: Discipline[] = [\n')

    for idx, d in enumerate(disciplines):
        f.write(f'  // ========== {idx+1}. {d["name"]} {d["nameEn"]} ==========\n')
        f.write('  {\n')
        f.write(f'    id: {json.dumps(d["id"])}, name: {json.dumps(d["name"])}, nameEn: {json.dumps(d["nameEn"])},\n')
        f.write(f'    icon: {json.dumps(d["icon"])}, color: {json.dumps(d["color"])},\n')
        f.write(f'    description: {json.dumps(d["description"])},\n')
        f.write('    glossary: [\n')
        for g in d["glossary"]:
            # Handle both dict (from make_discipline) and list (from JSON-serialized tuples)
            if isinstance(g, dict):
                t, te, df, cat = g["term"], g["termEn"], g["definition"], g["category"]
            else:
                t, te, df, cat = g[0], g[1], g[2], g[3]
            f.write(f'      {{ term: {json.dumps(t)}, termEn: {json.dumps(te)}, definition: {json.dumps(df)}, category: {json.dumps(cat)} }},\n')
        f.write('    ],\n')
        f.write('    formulas: [\n')
        for fo in d["formulas"]:
            unit_str = f', unit: {json.dumps(fo["unit"])}' if "unit" in fo else ""
            ref_str = f', reference: {json.dumps(fo["reference"])}' if "reference" in fo else ""
            f.write(f'      {{ name: {json.dumps(fo["name"])}, formula: {json.dumps(fo["formula"])}, description: {json.dumps(fo["description"])}{unit_str}{ref_str} }},\n')
        f.write('    ],\n')
        f.write('    standards: [\n')
        for s in d["standards"]:
            f.write(f'      {{ name: {json.dumps(s["name"])}, code: {json.dumps(s["code"])}, description: {json.dumps(s["description"])} }},\n')
        f.write('    ],\n')
        f.write('  },\n\n')

    f.write('];\n')

print(f"\n✅ Final TypeScript file written to {OUTPUT}")
