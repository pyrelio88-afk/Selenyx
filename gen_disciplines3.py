def make_discipline(did, dname, dnameEn, dicon, dcolor, ddesc, cats, formulas=None, standards=None):
    glossary = []
    for cat, terms in cats:
        for t in terms:
            glossary.append({"term": t[0], "termEn": t[1], "definition": t[2], "category": cat})
    return {"id": did, "name": dname, "nameEn": dnameEn, "icon": dicon, "color": dcolor,
            "description": ddesc, "glossary": glossary, "formulas": formulas or [], "standards": standards or []}

